def region_of(name):
    """Return the region of <source>-<region>.jsonl, which must have a catalog heading."""
    error = upload.region_error(name)
    if error:
        raise StopError(error)
    return name[: -len(".jsonl")].rsplit("-", 1)[1]


def esc(value):
    return html.escape(str(value))


def stated(value):
    """value as escaped HTML, or "Not stated" when it is null."""
    return '<span class="none">Not stated</span>' if value is None else esc(value)


def human_size(size):
    for unit, scale in (("GB", 10**9), ("MB", 10**6), ("kB", 10**3)):
        if size >= scale:
            return f"{size / scale:.1f} {unit}"
    return f"{size} bytes"


def stat(row, column):
    """A CORD_stats.csv cell as a number; a blank cell counts as 0."""
    return int(row.get(column) or 0)


def cord_id(name):
    """The in-page anchor of a catalog entry: its file name without .jsonl."""
    return name[: -len(".jsonl")]


def changelog_url(version, date):
    return f"{REPO_URL}/blob/{BASE}/CHANGELOG.md#{github_anchor(release_heading(version, date))}"


