def read_stats(root):
    """The rows of CORD_stats.csv keyed by (SOURCE, GEO); the first row wins."""
    path = os.path.join(root, STATS_CSV)
    if not os.path.exists(path):
        return {}
    rows = {}
    with open(path, encoding="utf-8", newline="") as file:
        for row in csv.DictReader(file):
            rows.setdefault((row["SOURCE"], row["GEO"]), row)
    return rows


def release_dates(text):
    """{version: date} for each ## [<version>] - <date> heading of CHANGELOG.md."""
    return {parse_version(m.group(1)): m.group(2) for m in RELEASE_HEADING.finditer(text)
            if parse_version(m.group(1))}


def catalog_entries(entries, cords, stats, dates):
    """Join each released manifest entry with its cords.json entry, stats row and date.

    Returns them sorted by name, each with "heading", "version", "date" and "stats" added.
    Stops on an unmapped region (released or not), a cords.json entry without a manifest
    entry, and a released file without a cords.json entry, stats row or CHANGELOG heading.
    """
    regions = {e["name"]: region_of(e["name"]) for e in entries}
    extra = sorted(set(cords) - set(regions))
    if extra:
        raise StopError(f"{CORDS_FILE}: no manifest.json entry for {', '.join(extra)}")
    result = []
    for entry in sorted((e for e in entries if e.get("tag")), key=lambda e: e["name"]):
        name, tag, region = entry["name"], entry["tag"], regions[entry["name"]]
        source = cord_id(name).rsplit("-", 1)[0]
        if name not in cords:
            raise StopError(f"{name}: no entry in {CORDS_FILE}")
        if (source, region) not in stats:
            raise StopError(f"{name}: no row with SOURCE {source} and GEO {region} in {STATS_CSV}")
        if parse_version(tag) not in dates:
            raise StopError(f"{name}: tag {tag} has no '## [{tag}] - <date>' heading in "
                            "CHANGELOG.md")
        result.append({**entry, **cords[name], "heading": upload.REGIONS[region],
                       "version": format_version(parse_version(tag)),
                       "date": dates[parse_version(tag)], "stats": stats[(source, region)]})
    return result


def commands_html(entry):
    return (f'<pre><code>curl -fsSLO {esc(entry["url"])}\n'
            f'echo "{esc(entry["sha256"])}  {esc(entry["name"])}" | sha256sum -c</code></pre>')


def source_html(source):
    if source is None or not source.get("url"):
        return stated(source and source.get("name"))
    return f'<a href="{esc(source["url"])}">{stated(source.get("name"))}</a>'


def cord_html(entry, related):
    """One catalog entry; related are the other entries under the same heading."""
    name, row = entry["name"], entry["stats"]
    facts = (
        ("Locale", esc(entry["heading"])),
        ("Primary source", source_html(entry["primary_source"])),
        ("License", stated(entry["license"])),
        ("Snapshot date", stated(entry["snapshot_date"])),
        ("Version", f'{esc(entry["version"])}, released {esc(entry["date"])} '
                    f'(<a href="{esc(changelog_url(entry["version"], entry["date"]))}">'
                    "changelog</a>)"),
        ("Size", f'{human_size(entry["size"])} ({entry["size"]:,} bytes)'),
        ("Records", f'{stat(row, "RECORD_COUNT"):,} ({stat(row, "PERSON_COUNT"):,} persons, '
                    f'{stat(row, "ORGANIZATION_COUNT"):,} organizations)'),
        ("DATA_SOURCE", f'<code>{stated(entry["data_source"])}</code>'),
        ("SHA-256", f'<code>{esc(entry["sha256"])}</code>'),
    )
    features = "".join(
        f'<li title="{stat(row, column):,}">{esc(column[: -len("_FEATURES")])}</li>'
        for column in row if column.endswith("_FEATURES") and stat(row, column)
    )
    sample = entry["sample_record"]
    sample = stated(None) if sample is None else esc(json.dumps(sample, indent=2,
                                                                ensure_ascii=False))
    links = ", ".join(f'<a href="#{esc(cord_id(e["name"]))}">{esc(e["name"])}</a>'
                      for e in related) or "None yet."
    return "\n".join((
        f'<article class="cord" id="{esc(cord_id(name))}">',
        f'<h3><a href="#{esc(cord_id(name))}">{esc(name)}</a></h3>',
        f'<p>{stated(entry["synopsis"])}</p>',
        "<dl>" + "".join(f"<div><dt>{term}</dt><dd>{value}</dd></div>"
                         for term, value in facts) + "</dl>",
        '<p class="label">Features</p>',
        f'<ul class="badges">{features}</ul>' if features else '<p class="none">None.</p>',
        '<p class="label">Download</p>',
        f'<p><a class="button" href="{esc(entry["url"])}">Download {esc(name)}</a></p>',
        commands_html(entry),
        f"<details><summary>Sample record</summary><pre><code>{sample}</code></pre></details>",
        f"<p>Related CORDs: {links}</p>",
        "</article>",
    ))


